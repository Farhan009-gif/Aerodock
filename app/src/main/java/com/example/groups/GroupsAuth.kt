package com.example.groups

import android.app.Activity
import android.content.Context
import android.content.ContextWrapper
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.example.R
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.flowOf

/**
 * Authentication for Groups: Google sign-in through Jetpack Credential
 * Manager, exchanged for a Firebase credential. The web client id comes from
 * `R.string.default_web_client_id`, generated by the google-services plugin
 * from the bundled google-services.json.
 */
class GroupsAuthRepository {

    private val auth: FirebaseAuth?
        get() = GroupsFirebase.auth()

    /** The user signed in right now, or null. Read once, synchronously. */
    fun currentUserSnapshot(): FirebaseUser? = try {
        auth?.currentUser
    } catch (e: Exception) {
        null
    }

    val currentUserFlow: Flow<FirebaseUser?> = if (GroupsFirebase.isAvailable) {
        callbackFlow {
            val firebaseAuth = GroupsFirebase.auth()
            if (firebaseAuth == null) {
                trySend(null)
                awaitClose { }
            } else {
                trySend(firebaseAuth.currentUser)
                val listener = FirebaseAuth.AuthStateListener { updated ->
                    trySend(updated.currentUser)
                }
                firebaseAuth.addAuthStateListener(listener)
                awaitClose { firebaseAuth.removeAuthStateListener(listener) }
            }
        }
    } else {
        flowOf(null)
    }

    /**
     * Launches the Google sign-in sheet. [context] should be the Activity
     * (or a context wrapping one) — Credential Manager needs a UI host.
     */
    suspend fun signInWithGoogle(context: Context): Result<FirebaseUser> {
        val firebaseAuth = auth
            ?: return Result.failure(IllegalStateException("Groups unavailable"))
        val hostContext = context.findActivity() ?: context
        return try {
            val credentialManager = CredentialManager.create(hostContext)
            val googleIdOption = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(context.getString(R.string.default_web_client_id))
                .setAutoSelectEnabled(false)
                .build()
            val request = GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build()
            val response = credentialManager.getCredential(hostContext, request)
            val credential = response.credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                val firebaseCredential = GoogleAuthProvider.getCredential(idToken, null)
                val task = firebaseAuth.signInWithCredential(firebaseCredential)
                task.awaitCompletion()
                val user = task.result?.user
                if (user != null) {
                    Result.success(user)
                } else {
                    Result.failure(IllegalStateException("Sign-in failed"))
                }
            } else {
                Result.failure(IllegalStateException("Unexpected credential type"))
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    fun signOut() {
        try {
            auth?.signOut()
        } catch (e: Exception) {
            // Fail soft: a failed sign-out must never crash the app.
        }
    }

    private tailrec fun Context.findActivity(): Activity? = when (this) {
        is Activity -> this
        is ContextWrapper -> baseContext.findActivity()
        else -> null
    }
}
